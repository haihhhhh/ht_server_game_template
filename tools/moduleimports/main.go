// moduleimports 生成 game 需要加载的业务包。请在模板项目根目录运行。
package main

import (
	"bytes"
	"embed"
	"errors"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"text/template"
)

//go:embed templates/imports.go.tmpl
var templates embed.FS

const moduleDirectory = "servers/game/internal/player/modules"

func generate() error {
	// 让 Go 识别当前平台的包与构建约束，只导入 modules 的直接子包。
	goCommand := filepath.Join(runtime.GOROOT(), "bin", "go")
	if runtime.GOOS == "windows" {
		goCommand += ".exe"
	}
	cmd := exec.Command(goCommand, "list", "-find", "./"+moduleDirectory+"/...")
	cmd.Stderr = os.Stderr
	output, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("查找业务包: %w", err)
	}
	var paths []string
	for _, path := range strings.Fields(string(output)) {
		_, name, ok := strings.Cut(path, "/"+moduleDirectory+"/")
		if ok && name != "generated" && !strings.Contains(name, "/") {
			paths = append(paths, path)
		}
	}
	sort.Strings(paths)
	layout, err := template.ParseFS(templates, "templates/imports.go.tmpl")
	if err != nil {
		return err
	}
	var source bytes.Buffer
	if err = layout.Execute(&source, paths); err != nil {
		return err
	}
	data, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	target := filepath.Join(moduleDirectory, "generated", "imports.gen.go")
	old, err := os.ReadFile(target)
	if err == nil {
		if bytes.Equal(old, data) {
			return nil
		}
		if !bytes.HasPrefix(old, []byte("// Code generated by moduleimports. DO NOT EDIT.")) {
			return fmt.Errorf("拒绝覆盖手写文件 %s", target)
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err = os.MkdirAll(filepath.Dir(target), 0755); err != nil {
		return err
	}
	// 完整写好再替换；生成被中断时，保留上一次可用的导入文件。
	temp, err := os.CreateTemp(filepath.Dir(target), ".imports-*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(temp.Name())
	if _, err = temp.Write(data); err != nil {
		_ = temp.Close()
		return err
	}
	if err = temp.Close(); err != nil {
		return err
	}
	return os.Rename(temp.Name(), target)
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
